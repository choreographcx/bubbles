<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"bpr-lede"} -->
<p class="bpr-lede">Everything people usually ask us before adopting, fostering, or helping out. If your question is not here, WhatsApp us on +971 50 808 3083.</p>
<!-- /wp:paragraph -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long does adoption take?</summary><!-- wp:paragraph -->
<p>Usually one to two weeks from application to homecoming. Our volunteer team reviews every application carefully, so first contact normally comes within one to three days, occasionally up to a week. You are always welcome to follow up on WhatsApp.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Why is there an adoption fee, and how much is it?</summary><!-- wp:paragraph -->
<p>Fees range from AED 800 to AED 4,000 depending on the rescue. Each animal we rehome has been sterilised, vaccinated, microchipped, treated, and often boarded for months. The fee reimburses part of that cost and goes directly into rescuing the next animal. It is non-refundable, except during the trial period.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I rent my home. Can I still adopt?</summary><!-- wp:paragraph -->
<p>Yes, many of our adopters rent. What matters is that your tenancy, building, or community rules permit the pet, with written approval where required. We will ask about this during screening, and it must be confirmed before placement.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What happens during a home check?</summary><!-- wp:paragraph -->
<p>A short visit or video call where we look at the space the animal will live in: window and balcony safety, escape points, and where they will sleep. It is not an inspection of your housekeeping, and we often suggest simple fixes rather than declining a home.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I have never owned a pet. Will you consider me?</summary><!-- wp:paragraph -->
<p>Absolutely. First-time owners are welcome for both adoption and fostering. We match first-timers with animals whose needs suit their experience, and we stay available for advice for as long as you need us.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do pets cope with the UAE summer?</summary><!-- wp:paragraph -->
<p>Very well, with the right routine: dogs walk in the early morning and late evening, never on hot pavement in the middle of the day, and all pets live indoors with air conditioning. Cats should be indoor-only, with screened windows and balconies. We talk this through with every adopter.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if I leave the UAE?</summary><!-- wp:paragraph -->
<p>Your pet goes with you. Relocating an animal is a well-trodden path from the UAE and usually far simpler than people expect; we can point you to trusted relocation services and explain typical costs. Adopters commit to including their pet in any move, and to contacting us first if circumstances make that genuinely impossible.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is there a trial period?</summary><!-- wp:paragraph -->
<p>Yes, we discuss a trial period before homecoming so both you and the animal can settle with a safety net. If it does not work out during the trial, the animal comes back to us and the fee is refunded as agreed.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I can no longer keep my pet. Will you take them?</summary><!-- wp:paragraph -->
<p>We are a small volunteer rescue and are almost always at capacity, so we cannot promise to take in surrendered pets. Contact us anyway: we can advise on responsible rehoming, share your pet with our network, and help you avoid the mistakes that put animals in danger. Never abandon an animal; it is dangerous and illegal in the UAE.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do adopted animals stay microchipped to the rescue?</summary><!-- wp:paragraph -->
<p>Yes. Every rescue remains microchipped under Bubbles Pet Rescue's name for lifelong traceability, and our adoption agreement requires that an animal is never sold, abandoned, or independently rehomed. If circumstances change, the animal comes back to us and we find the next right home together.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How can I help without adopting?</summary><!-- wp:paragraph -->
<p>Foster (even two weeks helps), donate supplies through our wishlist, help with transport or home checks, or simply share our rescues on social media. Every share genuinely finds homes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

