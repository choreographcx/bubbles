<!-- /wp:heading -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>You are 21 or over, and everyone in your household agrees to the adoption.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
