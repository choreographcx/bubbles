<p class="bpr-pill">About the Rescue</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"bpr-lede"} -->
<p class="bpr-lede">Bubbles Pet Rescue is a volunteer-run animal rescue in the UAE, dedicated to rescuing and rehoming stray, neglected, abandoned, abused, and surrendered pets.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"bpr-section-title"} -->
<h2 class="wp-block-heading bpr-section-title">Our story</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We are not a shelter, and we do not have a building full of kennels. Every animal in our care lives in a foster home, a boarding facility, a veterinary clinic, or with one of our volunteers until a forever home is found. That means every rescue we take on is a real, personal commitment: someone's spare room, someone's evening walks, someone's own money keeping the lights on.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>It started, as these things do, with one animal who needed help and people who could not look away. It has grown into a network of fosters, adopters, drivers, donors, and followers across the Emirates who believe the same simple thing: every pet deserves to be safe, understood, and loved for life.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"bpr-section-title"} -->
<h2 class="wp-block-heading bpr-section-title">Our mission</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>To rescue responsibly, support every pet's individual needs, and place them in homes where they will be safe for life. We would rather say no to a rescue than take on an animal we cannot properly care for, and we would rather wait months for the right adopter than say yes to the wrong one.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"bpr-section-title"} -->
